        qr.make(fit=True)
        img = qr.make_image(fill_color="black", back_color="white")
        img.save(temp_qr_path)
        
        # Process the QR image with the worker
        response_path = worker.process_qr_image(temp_qr_path)
        
        # Extract result from executed frames
        executed_frame = worker.executed_frames[-1] if worker.executed_frames else None
        
