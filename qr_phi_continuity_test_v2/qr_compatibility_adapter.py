#!/usr/bin/env python3
"""
QR Compatibility Adapter - Part of Animated QR Flipbook DNA System
By Vaughn Scott

This adapter bridges the gap between the simplified QR generator and the QR Worker.
It converts QR codes generated by the simplified generator into a format compatible with the QR Worker.
"""

import os
import sys
import json
import uuid
import time
import base64
import zlib
from datetime import datetime
from PIL import Image
from pyzbar.pyzbar import decode
import qrcode

class QRCompatibilityAdapter:
    """
    Adapter to make QR codes compatible between different components of the QR Flipbook DNA System.
    """
    
    def __init__(self, output_dir="qr_compatible", verbose=True):
        """
        Initialize the QR compatibility adapter.
        
        Args:
            output_dir: Directory to save compatible QR codes
            verbose: Whether to print verbose output
        """
        self.output_dir = output_dir
        self.verbose = verbose
        
        # Create output directory
        os.makedirs(output_dir, exist_ok=True)
    
    def decompress_payload(self, payload):
        """
        Decompress payload using zlib and base64 decode.
        
        Args:
            payload: Compressed payload with marker
            
        Returns:
            Decompressed payload
        """
        if payload.startswith("COMPRESSED:"):
            encoded = payload.replace("COMPRESSED:", "", 1)
            compressed = base64.b64decode(encoded)
            decompressed = zlib.decompress(compressed)
            return decompressed.decode('utf-8')
        return payload
    
    def decode_qr_image(self, image_path):
        """
        Decode QR code from image.
        
        Args:
            image_path: Path to QR code image
            
        Returns:
            Decoded payload or None if decoding failed
        """
        if self.verbose:
            print(f"Decoding QR image: {image_path}")
        
        try:
            # Open image
            image = Image.open(image_path)
            
            # Try decoding with pyzbar
            decoded_objects = decode(image)
            
            # Return decoded data if found
            if decoded_objects:
                data = decoded_objects[0].data.decode('utf-8')
                
                # Check if payload is compressed
                if data.startswith("COMPRESSED:"):
                    if self.verbose:
                        print("Detected compressed payload, decompressing...")
                    data = self.decompress_payload(data)
                
                if self.verbose:
                    print(f"Successfully decoded QR code")
                
                return data
            
            if self.verbose:
                print("No QR code found in image")
            
            return None
        except Exception as e:
            if self.verbose:
                print(f"Error decoding QR code: {e}")
            return None
    
    def convert_to_worker_format(self, payload_json, frame_number):
        """
        Convert payload from simplified format to QR Worker format.
        
        Args:
            payload_json: JSON payload from simplified generator
            frame_number: Frame number
            
        Returns:
            Payload in QR Worker format
        """
        try:
            # Parse JSON payload
            payload = json.loads(payload_json)
            
            # Extract data
            code = payload.get("code", "")
            task_type = payload.get("task_type", "execute_python")
            phi_state = payload.get("phi_state", {})
            
            # Create session ID if not present
            session_id = str(uuid.uuid4())
            
            # Create worker format payload
            worker_payload = {
                "session_id": session_id,
                "frame_number": frame_number,
                "task_type": task_type,
                "content": code,
                "phi_metadata": {
                    "generation": phi_state.get("generation", 1),
                    "complexity": phi_state.get("complexity", 0.618),
                    "resonance": phi_state.get("resonance", 1.618)
                },
                "timestamp": datetime.now().isoformat()
            }
            
            return worker_payload
        except Exception as e:
            if self.verbose:
                print(f"Error converting payload to worker format: {e}")
            return None
    
    def generate_worker_compatible_qr(self, worker_payload, frame_number):
        """
        Generate QR code in QR Worker compatible format.
        
        Args:
            worker_payload: Payload in QR Worker format
            frame_number: Frame number
            
        Returns:
            Path to generated QR image
        """
        # Convert payload to JSON
        json_payload = json.dumps(worker_payload)
        
        # Create QR code
        qr = qrcode.QRCode(
            version=None,
            error_correction=qrcode.constants.ERROR_CORRECT_H,
            box_size=10,
            border=4,
        )
        qr.add_data(json_payload)
        qr.make(fit=True)
        
        # Create image
        img = qr.make_image(fill_color="black", back_color="white")
        
        # Save image
        filename = f"qr_worker_frame_{frame_number:03d}.png"
        filepath = os.path.join(self.output_dir, filename)
        img.save(filepath)
        
        if self.verbose:
            print(f"Generated worker-compatible QR code: {filepath}")
        
        return filepath
    
    def convert_qr_sequence(self, input_dir, output_dir=None):
        """
        Convert QR sequence from simplified format to QR Worker format.
        
        Args:
            input_dir: Directory containing QR code images in simplified format
            output_dir: Optional output directory override
            
        Returns:
            List of paths to converted QR images
        """
        if output_dir:
            self.output_dir = output_dir
            os.makedirs(output_dir, exist_ok=True)
        
        if self.verbose:
            print(f"Converting QR sequence from {input_dir} to {self.output_dir}...")
        
        # Get all QR files
        qr_files = sorted([f for f in os.listdir(input_dir) if f.startswith("qr_frame_") and f.endswith(".png")])
        
        if not qr_files:
            if self.verbose:
                print("No QR code files found!")
            return []
        
        if self.verbose:
            print(f"Found {len(qr_files)} QR code files")
        
        # Convert each QR file
        converted_paths = []
        for i, qr_file in enumerate(qr_files):
            frame_number = i + 1
            qr_path = os.path.join(input_dir, qr_file)
            
            if self.verbose:
                print(f"\nConverting QR file {frame_number}/{len(qr_files)}: {qr_path}")
            
            # Decode QR code
            payload_json = self.decode_qr_image(qr_path)
            
            if payload_json:
                # Convert payload to worker format
                worker_payload = self.convert_to_worker_format(payload_json, frame_number)
                
                if worker_payload:
                    # Generate worker-compatible QR code
                    path = self.generate_worker_compatible_qr(worker_payload, frame_number)
                    converted_paths.append(path)
                else:
                    if self.verbose:
                        print("Failed to convert payload to worker format")
            else:
                if self.verbose:
                    print("Failed to decode QR code")
        
        if self.verbose:
            print(f"\nConverted {len(converted_paths)}/{len(qr_files)} QR code files")
        
        return converted_paths
