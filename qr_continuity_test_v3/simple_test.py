# Simple test script for QR code conversion

def main():
    print("Hello from the Quantum Phi-Harmonic System!")
    print("This script was encoded in a QR code and successfully executed.")
    
    # Calculate and display the golden ratio
    phi = (1 + 5**0.5) / 2
    print(f"\nThe golden ratio (φ) is: {phi}")
    
