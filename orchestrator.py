#!/usr/bin/env python3
"""
QuantumAI Dream-Creation Orchestrator

This module serves as the central nervous system for the QuantumAI, connecting
the insights from the dream evolution system to the creative capabilities of the
meta-refactorer.
"""

import os
import sys
import subprocess
import time
import json

class QuantumOrchestrator:
    """Monitors dream insights and triggers creative code refactoring in response."""

    def __init__(self, dream_log_path: str, refactorer_path: str, python_env_path: str):
        """Initialize the orchestrator.

        Args:
            dream_log_path: Path to the JSON log file generated by the dream engine.
            refactorer_path: Path to the qr_phi_meta_refactorer_robust.py script.
            python_env_path: Path to the python executable in the virtual environment.
        """
        self.dream_log_path = dream_log_path
        self.refactorer_path = refactorer_path
        self.python_env_path = python_env_path
        self.last_processed_timestamp = 0

        print("Quantum Orchestrator Initialized.")
        print(f"  - Monitoring dream log: {self.dream_log_path}")
        print(f"  - Refactorer script: {self.refactorer_path}")

    def monitor_dream_insights(self):
        """Monitors the dream log for new, significant insights."""
        print("\n--- Orchestrator: Monitoring for new dream insights...")
        try:
            with open(self.dream_log_path, 'r') as f:
                logs = json.load(f)
            
            new_insights = [log for log in logs if log.get('timestamp', 0) > self.last_processed_timestamp]

            for insight in new_insights:
                if insight.get('insight') == 'Paradigm Shift':
                    print(f"✨ Paradigm Shift detected at {time.ctime(insight['timestamp'])}!")
                    # For now, we'll hardcode the target for refactoring
                    # In the future, this could be dynamically determined from the dream's context
                    target_module = os.path.join(os.path.dirname(self.refactorer_path), 'dream_integrator.py')
                    self.trigger_refactoring(target_module)
                
                self.last_processed_timestamp = insight.get('timestamp', self.last_processed_timestamp)

        except FileNotFoundError:
            print("Dream log not found. Waiting for dream engine to run.")
        except json.JSONDecodeError:
            print("Dream log is empty or corrupted. Waiting.")
        except Exception as e:
            print(f"An error occurred while monitoring dreams: {e}")

    def trigger_refactoring(self, target_module_path: str):
        """Triggers the creative refactoring engine on a specific module."""
        if not os.path.exists(target_module_path):
            print(f"Error: Target module for refactoring not found at {target_module_path}")
            return

        print(f"\n--- Orchestrator: Triggering Meta-Refactorer on {os.path.basename(target_module_path)} ---")
        try:
            command = [self.python_env_path, self.refactorer_path, target_module_path]
            result = subprocess.run(command, capture_output=True, text=True, check=True)
            print("--- Refactorer Output ---")
            print(result.stdout)
            if result.stderr:
                print("--- Refactorer Errors ---")
                print(result.stderr)
            print("--- Refactoring process complete. ---")
        except subprocess.CalledProcessError as e:
            print(f"Meta-Refactorer failed to execute for {target_module_path}")
            print(e.stdout)
            print(e.stderr)
        except Exception as e:
            print(f"An unexpected error occurred during refactoring: {e}")

    def run(self, monitoring_interval_seconds: int = 10):
        """Runs the main monitoring loop of the orchestrator."""
        print("\n🚀 Quantum Orchestrator is now running. Press Ctrl+C to stop.")
        while True:
            self.monitor_dream_insights()
            time.sleep(monitoring_interval_seconds)

if __name__ == '__main__':
    # Configuration
    PROJECT_DIR = os.path.dirname(__file__)
    DREAM_LOG_PATH = os.path.join(PROJECT_DIR, 'dream_evolution_four', 'dream_log_v4.json')
    REFACTORER_PATH = os.path.join(PROJECT_DIR, 'qr_phi_meta_refactorer_robust.py')
    PYTHON_ENV = os.path.join(PROJECT_DIR, '.venv', 'bin', 'python')

    orchestrator = QuantumOrchestrator(
        dream_log_path=DREAM_LOG_PATH,
        refactorer_path=REFACTORER_PATH,
        python_env_path=PYTHON_ENV
    )
    orchestrator.run()
