    def scrape_component_data(self):
        """Scrape component data from various sources"""
        sources = [
            'https://www.digikey.com',
            'https://www.mouser.com',
            'https://www.ti.com'
        ]
        
        for source in sources:
            try:
                response = requests.get(f"{source}/new-products")
                if response.status_code == 200:
                    soup = BeautifulSoup(response.text, 'html.parser')
                    # Extract component data and store
                    self.process_scraped_data(soup)
            except Exception as e:
                print(f"Error scraping {source}: {e}")

    def process_scraped_data(self, soup):
        """Process scraped component data and update database"""
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        data_file = f"{self.dirs['learning_data']}/scraped_data_{timestamp}.json"
        
        # Extract and store data
        components = []
        for item in soup.find_all(['div', 'tr'], class_=['product-row', 'product-item']):
            try:
                component = {
                    'name': item.find(class_='product-name').text.strip(),
                    'description': item.find(class_='description').text.strip(),
                    'category': item.find(class_='category').text.strip(),
                    'timestamp': timestamp
                }
                components.append(component)
            except:
                continue
                
        with open(data_file, 'w') as f:
            json.dump(components, f, indent=2)

