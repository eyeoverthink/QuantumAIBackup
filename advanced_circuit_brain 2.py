    def create_complex_circuit(self, components: List[str]) -> str:
        """Create a complex circuit with multiple components"""
        d = schemdraw.Drawing()
        
        # Add power and ground
        d += (Vdd := elm.SourceV().label('Vdd').up())
        d += elm.Line().right()
        
        # Add components
        x, y = d.here
        for i, comp_type in enumerate(components):
            if comp_type in self.ic_chips:
                # Add IC chip
                chip = self.ic_chips[comp_type]
                d += (IC := elm.Dot().at((x + i*3, y)).label(chip.name))
            elif comp_type in self.logic_gates:
                # Add logic gate
                d += (Gate := elm.Dot().at((x + i*3, y)).label(comp_type))
            
        # Complete the circuit
        d += elm.Line().down()
        d += elm.Ground()
        
        # Save the schematic
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        schematic_file = f"{self.dirs['schematics']}/circuit_{timestamp}.png"
        d.save(schematic_file)
        
        return schematic_file

