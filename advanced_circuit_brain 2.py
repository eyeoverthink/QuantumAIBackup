    def get_circuit_suggestions(self, components: List[str]) -> List[dict]:
        """Get circuit suggestions based on components"""
        suggestions = []
        
        # Check circuit ideas for matching components
        for idea in self.knowledge_extractor.knowledge_base['circuit_ideas']:
            if any(comp.lower() in [c.lower() for c in idea['components']] for comp in components):
                suggestions.append({
                    'description': idea['description'],
                    'circuit_type': idea['circuit_type'],
                    'additional_components': [c for c in idea['components'] if c not in components],
                    'modifications': idea['modifications'],
                    'applications': idea['applications']
                })
        
        # Check design patterns
        for pattern in self.knowledge_extractor.knowledge_base['design_patterns'].values():
            if any(comp.lower() in [c.lower() for c in pattern['components']] for comp in components):
                suggestions.append({
                    'description': pattern['description'],
                    'circuit_type': 'design_pattern',
                    'additional_components': [c for c in pattern['components'] if c not in components],
                    'context': pattern['context']
                })
                
        # Check applications
        for app in self.knowledge_extractor.knowledge_base['applications'].values():
            if any(comp.lower() in [c.lower() for c in app['components']] for comp in components):
                suggestions.append({
                    'description': app['description'],
                    'circuit_type': 'application',
                    'additional_components': [c for c in app['components'] if c not in components],
                    'circuits': app['circuits']
                })
                
        return suggestions
        
