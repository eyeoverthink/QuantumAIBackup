"""
Quantum Question Answering API

This module provides a Flask API for the Quantum Question Answering system.
It allows users to ask any question and receive answers generated by the
quantum-enhanced AI system.
"""

import os
import sys
from pathlib import Path
import json
from datetime import datetime
from flask import Flask, request, jsonify, render_template
from flask_cors import CORS

# Add the project root to Python path
project_root = str(Path(__file__).parent.parent.parent)
if project_root not in sys.path:
    sys.path.append(project_root)

# Import the QuantumQAIntegration
from deep_learning.integrations.quantum_qa_integration import QuantumQAIntegration

# Initialize Flask app
app = Flask(__name__, 
            template_folder=os.path.join(project_root, 'templates'),
            static_folder=os.path.join(project_root, 'static'))

# Enable CORS
CORS(app)

# Initialize the QA system
qa_integration = QuantumQAIntegration()

@app.route('/')
def index():
    """Render the QA interface"""
    return render_template('quantum_qa.html')

@app.route('/api/qa/answer', methods=['POST'])
def answer_question():
    """Process a question and return an answer"""
    data = request.get_json()
    question = data.get('question', '')
    brain_type = data.get('brain_type', 'Standard')
    max_length = int(data.get('max_length', 150))
    
    # Process the question
    result = qa_integration.answer_question(question, brain_type, max_length)
    
    # Return the result
    return jsonify({
        'status': 'success',
        'result': result
    })

@app.route('/api/qa/dna/retrieve/<dna_id>', methods=['GET'])
def retrieve_from_dna(dna_id):
    """Retrieve information from DNA storage"""
    result = qa_integration.retrieve_from_dna(dna_id)
    
    if result:
        return jsonify({
            'status': 'success',
            'result': result
        })
    else:
        return jsonify({
            'status': 'error',
            'message': f'DNA sequence with ID {dna_id} not found'
        }), 404

@app.route('/api/qa/dna/search', methods=['POST'])
def search_dna():
    """Search the DNA storage for relevant information"""
    data = request.get_json()
    query = data.get('query', '')
    limit = int(data.get('limit', 5))
    
    results = qa_integration.search_dna_storage(query, limit)
    
    return jsonify({
        'status': 'success',
        'results': results
    })

@app.route('/api/qa/metrics', methods=['GET'])
def get_metrics():
    """Get system metrics"""
    # Count DNA sequences
    dna_storage_path = os.path.join(project_root, "deep_learning", "dna_storage")
    dna_count = len([f for f in os.listdir(dna_storage_path) if f.endswith('.json')]) if os.path.exists(dna_storage_path) else 0
    
    # Get logs
    log_dir = os.path.join(project_root, "deep_learning", "logs")
    log_files = [f for f in os.listdir(log_dir) if f.startswith('qa_integration_log_')] if os.path.exists(log_dir) else []
    
    # Calculate query count from most recent log
    query_count = 0
    if log_files:
        log_files.sort(reverse=True)
        log_path = os.path.join(log_dir, log_files[0])
        
        with open(log_path, 'r') as f:
            logs = json.load(f)
            query_count = sum(1 for log in logs if log['event_type'] == 'question_received')
    
    return jsonify({
        'status': 'success',
        'metrics': {
            'dna_sequence_count': dna_count,
            'query_count': query_count,
            'system_uptime': '1d 4h 23m',  # Placeholder
            'last_updated': datetime.now().isoformat()
        }
    })

if __name__ == '__main__':
    # Ensure directories exist
    os.makedirs(os.path.join(project_root, "deep_learning", "dna_storage"), exist_ok=True)
    os.makedirs(os.path.join(project_root, "deep_learning", "logs"), exist_ok=True)
    
    # Run the app
    app.run(host='127.0.0.1', port=5004, debug=True)
